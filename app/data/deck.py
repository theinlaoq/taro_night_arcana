def _answer(value: str) -> str:
    return "yes" if value == "y" else "no"


def _build_deck() -> tuple[CardDefinition, ...]:
    raw_cards: list[tuple[str, str, str, str, str, str | None]] = [
        (card_id, name, meaning_up, meaning_reversed, "Старший аркан", None)
        for card_id, name, meaning_up, meaning_reversed in MAJOR
    ]

    for suit_key, name_suffix, arcana, element, meanings in SUITS:
        for index, (meaning_up, meaning_reversed) in enumerate(meanings, start=1):
            raw_cards.append(
                (
                    f"{suit_key}{index:02}",
                    f"{RANKS[index - 1]} {name_suffix}",
                    meaning_up,
                    meaning_reversed,
                    arcana,
                    element,
                )
            )

    if len(raw_cards) != len(YESNO_UP) or len(raw_cards) != len(YESNO_REVERSED):
        raise ValueError("Yes/no tables must contain exactly one answer per card")

    return tuple(
        CardDefinition(
            id=card_id,
            name=name,
            arcana=arcana,
            element=element,
            meaningUp=meaning_up,
            meaningReversed=meaning_reversed,
            yesNoUp=_answer(YESNO_UP[index]),
            yesNoReversed=_answer(YESNO_REVERSED[index]),
            imageUrl=f"/cards/{card_id}.jpg",
        )
        for index, (card_id, name, meaning_up, meaning_reversed, arcana, element) in enumerate(
            raw_cards
        )
    )


DECK = _build_deck()
CARDS_BY_ID = {card.id: card for card in DECK}
